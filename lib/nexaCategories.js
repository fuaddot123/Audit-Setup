export function nexaCategory(item) {
  const code = String(item.sku || "").trim().toUpperCase().split("-")[1];
  return nexaCategoryNames[code] || item.category || "Belum terpetakan";
}
export const discrepancyCategory = (item) => item.difference < 0 ? "Stok kurang" : item.difference > 0 ? "Stok lebih" : "Cocok";
